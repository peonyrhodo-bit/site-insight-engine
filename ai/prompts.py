def build_chat_prompt(
    message: str,
    *,
    context: Mapping[str, Any] | None = None,
) -> str:
    instructions = """
Пользователь обратился к Director.

Пойми смысл сообщения и определи,
какое действие или изменение состояния проекта
пользователь фактически ожидает.

Не ограничивайся буквальным ответом на текст.

Если пользователь просит:

- исследовать — сформулируй исследовательское намерение;
- найти возможность — выдели объект анализа;
- создать рекомендацию — подготовь структуру рекомендации;
- изменить приоритет — зафиксируй предполагаемое изменение;
- принять/отклонить рекомендацию — зафиксируй это как feedback;
- уточнить — сформулируй необходимый вопрос.

Если информации недостаточно для безопасного действия,
сформулируй уточняющий вопрос.
""".strip()

    payload = {
        "user_message": message,
        "director_context": dict(context or {}),
    }

    return _compose_task(
        instructions,
        payload,
    )


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------


def _compose_task(
    instructions: str,
    context: Mapping[str, Any],
) -> str:
    context_text = _serialize_context(context)

    return (
        f"{instructions}\n\n"
        "Контекст Director:\n"
        f"{context_text}"
    )


def _serialize_context(
    context: Mapping[str, Any],
) -> str:
    import json

    try:
        return json.dumps(
            dict(context),
            ensure_ascii=False,
            indent=2,
            default=str,
        )
    except Exception:
        return str(dict(context))


