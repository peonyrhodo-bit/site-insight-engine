# ai/prompts.py
"""
System prompts and prompt builders for the AI Director.

This module contains the intellectual instructions given to the AI model.

Important boundary:

AI model = reasoning instrument.
Director = strategic system.

The prompts must therefore teach the model to support Director logic,
not replace the Director architecture.
"""

