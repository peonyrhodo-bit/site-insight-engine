PROMPT_REGISTRY: dict[str, str] = {
    "system": DIRECTOR_SYSTEM_PROMPT,
    "analysis": ANALYSIS_INSTRUCTIONS,
    "decision": DECISION_INSTRUCTIONS,
    "recommendation": RECOMMENDATION_INSTRUCTIONS,
    "question": QUESTION_INSTRUCTIONS,
    "hypothesis": (
        "Формулирование проверяемой гипотезы "
        "для YouTube-проекта."
    ),
    "chat": (
        "Интерпретация пользовательского сообщения "
        "как намерения Director."
    ),
}


def get_system_prompt() -> str:
    return DIRECTOR_SYSTEM_PROMPT


def get_prompt(
    prompt_type: str,
) -> str:
    key = (prompt_type or "").strip().lower()

    if key not in PROMPT_REGISTRY:
        raise KeyError(
            f"Unknown Director prompt type: {prompt_type}"
        )

    return PROMPT_REGISTRY[key]


