-- Quota ledger used only by the Director's server-side PostgreSQL connection.
-- The private schema is deliberately not exposed through Supabase's public Data API.
CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC;
REVOKE ALL ON SCHEMA private FROM anon, authenticated;

CREATE TABLE IF NOT EXISTS private.youtube_quota_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  operation text NOT NULL,
  search_calls integer NOT NULL DEFAULT 0 CHECK (search_calls >= 0),
  other_units integer NOT NULL DEFAULT 0 CHECK (other_units >= 0),
  metadata_json jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS youtube_quota_usage_created_at_idx
  ON private.youtube_quota_usage (created_at);

CREATE TABLE IF NOT EXISTS private.youtube_quota_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  operation text NOT NULL,
  method text NOT NULL,
  bucket text NOT NULL CHECK (bucket IN ('search', 'other')),
  units integer NOT NULL CHECK (units > 0),
  status text NOT NULL,
  reason text,
  remaining_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  metadata_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  finished_at timestamptz
);
CREATE INDEX IF NOT EXISTS youtube_quota_events_created_at_idx
  ON private.youtube_quota_events (created_at DESC);
CREATE INDEX IF NOT EXISTS youtube_quota_events_status_idx
  ON private.youtube_quota_events (status);

REVOKE ALL ON ALL TABLES IN SCHEMA private FROM PUBLIC, anon, authenticated;
